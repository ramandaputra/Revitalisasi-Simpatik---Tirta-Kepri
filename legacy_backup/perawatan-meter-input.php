    <script>
        $(document).ready(function() {
            // Set default value for Periode
            var date = new Date();
            date.setMonth(date.getMonth() - 1);
            var year = date.getFullYear();
            var month = (date.getMonth() + 1).toString().padStart(2, '0');
            $('#periode').val(`${year}-${month}`);

            $('#wilayah, #periode').change(function() {
                var selectedWilayah = $('#wilayah').val();
                var selectedPeriode = $('#periode').val().replace("-", "");
                fetchData(selectedWilayah, selectedPeriode);
            });

            // Function to fetch data
            function fetchData(wilayah, periode) {
                $.ajax({
                    url: 'assets/data/get-data/perawatan-meter-input.php',
                    method: 'GET',
                    data: {
                        wilayah: wilayah,
                        periode: periode
                    },
                    success: function(data) {
                        console.log('Raw server response:', data); // Log raw response
                        try {
                            var result = JSON.parse(data); // Parse the response
                            console.log('Parsed result:', result); // Log parsed result
                            $('#data2').val(Number(result.data2).toLocaleString('id-ID'));
                            // Call a function or add logic here if needed
                        } catch (e) {
                            console.error('Invalid JSON response:', e);
                            $('#data2').val('Invalid JSON');
                        }
                    },
                    error: function(xhr, status, error) {
                        console.error('Error fetching data:', error);
                    }
                });
            }

            // Posting data
            $('#postingData').click(function() {
                var data = {
                    wilayah: $('#wilayah').val(),
                    periode: $('#periode').val(),
                    data1: $('#data1').val().replace(/\./g, ''), // Remove all dots (thousand separator)
                    data2: $('#data2').val().replace(/\./g, '')
                };

                $.ajax({
                    url: 'assets/data/save-data/perawatan-meter-input.php',
                    method: 'POST',
                    data: data,
                    success: function(response) {
                        alert(response);
                    },
                    error: function(xhr, status, error) {
                        console.error('Error posting data:', error);
                    }
                });
            });
        });
    </script>
